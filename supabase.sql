create table if not exists public.assessments (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  timestamp text not null,
  model text not null,
  cleanliness double precision,
  quality double precision,
  age_range text,
  description text,
  limitations text,
  morning jsonb not null default '[]'::jsonb,
  evening jsonb not null default '[]'::jsonb,
  preferences jsonb not null default '{}'::jsonb
);

alter table public.assessments enable row level security;

create policy "Users can view their assessments"
on public.assessments for select
using (auth.uid() = user_id);

create policy "Users can insert their assessments"
on public.assessments for insert
with check (auth.uid() = user_id);

create policy "Users can delete their assessments"
on public.assessments for delete
using (auth.uid() = user_id);
